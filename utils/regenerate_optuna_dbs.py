#!/usr/bin/env python
"""Regenerate the precomputed optuna databases stored in content/optuna.

The notebooks `single_horizon_prediction` and `multiple_horizons_prediction`
reload these databases and only add a couple of iterations to keep execution
fast. This script runs the full searches.

The pipelines are not redefined here: they are imported from the `*_lib.py`
modules generated by `utils/extract_defs.py` (run `pixi run
scrape-function-definitions` first, or use the `regenerate-optuna-dbs` pixi
task which does it).

The study names, scoring, and data window must be kept in sync with the
corresponding notebooks.
"""

import argparse
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PYTHON_FILES = REPO / "content" / "python_files"
OPTUNA_DIR = REPO / "content" / "optuna"

STUDY_NAME = "randomized_search"


def search_single_horizon_ridge(storage, n_iter, n_jobs):
    from feature_engineering_lib import feature_engineering_outputs
    from single_horizon_prediction_lib import TimeSeriesSplitter, make_ridge_predictions

    features, y = feature_engineering_outputs(horizons=12, cv_splitter=TimeSeriesSplitter())
    predictions_ridge = make_ridge_predictions(features, y)
    search = predictions_ridge.skb.make_randomized_search(
        backend="optuna",
        storage=storage,
        study_name=STUDY_NAME,
        refit="r2",
        n_iter=n_iter,
        fitted=True,
        verbose=1,
        n_jobs=n_jobs,
    )
    return search


def search_multiple_horizons(storage, n_iter, n_jobs):
    from feature_engineering_lib import feature_engineering_outputs
    from multiple_horizons_prediction_lib import make_multi_horizon_pred, neg_mape_scorer
    from single_horizon_prediction_lib import TimeSeriesSplitter

    time_horizons = (1, 12, 24)
    features, y = feature_engineering_outputs(time_horizons, cv_splitter=TimeSeriesSplitter())
    pred = make_multi_horizon_pred(features, y).skb.with_scoring(neg_mape_scorer)
    search = pred.skb.make_randomized_search(
        backend="optuna",
        storage=storage,
        study_name=STUDY_NAME,
        n_iter=n_iter,
        n_jobs=n_jobs,
        refit="neg_mape_average",
        fitted=True,
    )
    return search


# Maps the name of the database file to the function running the search.
SEARCHES = {
    "single_horizon_prediction_ridge": search_single_horizon_ridge,
    "multiple_horizons_prediction": search_multiple_horizons,
}


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "names",
        nargs="*",
        choices=list(SEARCHES),
        help=f"Databases to regenerate (default: all). Choices: {', '.join(SEARCHES)}.",
    )
    parser.add_argument("--n-iter", type=int, default=128, help="Number of iterations.")
    parser.add_argument("--n-jobs", type=int, default=4, help="Number of parallel jobs.")
    parser.add_argument(
        "--output-dir", type=Path, default=OPTUNA_DIR, help="Where to write the databases."
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Resume existing studies and add --n-iter more iterations, instead of "
        "deleting the existing databases and starting from scratch.",
    )
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    names = args.names or list(SEARCHES)
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    # The notebooks locate the datasets relative to the working directory
    # (`../datasets`) and import tutorial_helpers and the *_lib modules.
    os.chdir(PYTHON_FILES)
    sys.path.insert(0, str(PYTHON_FILES))

    for name in names:
        db_path = output_dir / f"{name}.optuna"
        if not args.resume and db_path.exists():
            db_path.unlink()
        sys.stderr.write(f"Running {args.n_iter} iterations for {name} -> {db_path}\n")
        SEARCHES[name](f"sqlite:///{db_path}", args.n_iter, args.n_jobs)
        sys.stderr.write(f"Wrote {db_path}\n")


if __name__ == "__main__":
    main()
